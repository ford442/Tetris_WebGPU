#!/usr/bin/env node
/**
 * Generates the C++ authored-material constants from public/block-material.json,
 * the same file the TS and WebGL2 renderers fetch at runtime.
 *
 * Before this existed, gpu_renderer.cpp carried its own `kAuthoredGlassMin = 0.28f`
 * next to the TS renderer's 0.05 — exactly the silent drift the visual contract is
 * meant to make impossible. Now there is one number and one place to change it.
 *
 * Output: cpp/src/generated/authored_block_material.h (gitignored, regenerated every
 * run). Pure Node/fs, no emcc required.
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

import { MATERIAL_PATH, readValidatedMaterial } from './lib/blockMaterialSchema.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const OUT_DIR = join(ROOT, 'cpp', 'src', 'generated');
const OUT_HEADER = join(OUT_DIR, 'authored_block_material.h');

function f(value) {
  return `${Number(value).toFixed(6)}f`;
}

function main() {
  const m = readValidatedMaterial();

  const header = `#pragma once
// GENERATED by scripts/generate-cpp-material.mjs — do not edit.
// Source of truth: ${relative(ROOT, MATERIAL_PATH)} (validated against
// shared/blockMaterialSchema.json). Edit the JSON, rebuild, never this file.
//
// Material: ${m.name}

#include "authored_block_uniforms.h"

namespace tetris {

// Glass opacity curve + screen-space refraction (TS: GlassParams / GlassRefractionParams).
constexpr float kAuthoredGlassMin = ${f(m.glass.min)};
constexpr float kAuthoredGlassMax = ${f(m.glass.max)};
constexpr float kAuthoredGlassFresnelPower = ${f(m.glass.fresnelPower)};
constexpr float kAuthoredGlassIor = ${f(m.glass.ior)};
constexpr float kAuthoredGlassThickness = ${f(m.glass.thickness)};

// Jewelry gold grade (TS: gradeGoldMetalAlbedoTinted arguments).
constexpr float kAuthoredGoldTint[3] = {${f(m.gold.tint[0])}, ${f(m.gold.tint[1])}, ${f(m.gold.tint[2])}};
constexpr float kAuthoredGoldMix = ${f(m.gold.mix)};
constexpr float kAuthoredGoldShadeMin = ${f(m.gold.shadeMin)};
constexpr float kAuthoredGoldShadeMax = ${f(m.gold.shadeMax)};

// Roughness band + normal strength (TS: AuthoredMaterialParams.goldShade/mapParams).
constexpr float kAuthoredMetalRoughness = ${f(m.roughness.metal)};
constexpr float kAuthoredGlassRoughness = ${f(m.roughness.glass)};
constexpr float kAuthoredRoughnessDetail = ${f(m.roughness.detail)};
constexpr float kAuthoredNormalStrength = ${f(m.normal.strength)};

/**
 * Fill the authored-material half of the uniform block. \`material_map_bound\` is 1
 * once set_block_material_map_rgba() has uploaded a baked packed map; until then the
 * shader uses the contract fallback, exactly like the TS path's flat 1x1 texture.
 */
inline void fill_authored_material_uniforms(AuthoredBlockUniforms& u, float material_map_bound) {
  u.glassParams[0] = kAuthoredGlassMin;
  u.glassParams[1] = kAuthoredGlassMax;
  u.glassParams[2] = kAuthoredGlassFresnelPower;
  u.glassParams[3] = 0.0f;

  u.goldTint[0] = kAuthoredGoldTint[0];
  u.goldTint[1] = kAuthoredGoldTint[1];
  u.goldTint[2] = kAuthoredGoldTint[2];
  u.goldTint[3] = kAuthoredGoldMix;

  u.goldShade[0] = kAuthoredGoldShadeMin;
  u.goldShade[1] = kAuthoredGoldShadeMax;
  u.goldShade[2] = kAuthoredMetalRoughness;
  u.goldShade[3] = kAuthoredGlassRoughness;

  u.mapParams[0] = kAuthoredNormalStrength;
  u.mapParams[1] = material_map_bound;
  u.mapParams[2] = kAuthoredRoughnessDetail;
  u.mapParams[3] = 0.0f; // debug view: TS-only (dev hotkey)
}

} // namespace tetris
`;

  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(OUT_HEADER, header);
  console.log(`[generate-cpp-material] Wrote ${OUT_HEADER} from ${relative(ROOT, MATERIAL_PATH)}`);
}

main();
