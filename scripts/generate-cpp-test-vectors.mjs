#!/usr/bin/env node
/**
 * Emits cpp/tests/generated/parity_vectors.h from shared/cppParityVectors.json so the
 * host-side doctest suite asserts the same literal numbers the TS parity test does.
 * Pure Node, no emcc. Run by `npm run cpp:test:native` and by the CMake test target.
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(ROOT, 'shared', 'cppParityVectors.json');
const OUT_DIR = join(ROOT, 'cpp', 'tests', 'generated');
const OUT_HEADER = join(OUT_DIR, 'parity_vectors.h');

const v = JSON.parse(readFileSync(SOURCE, 'utf8'));

const num = (n) => (Number.isInteger(n) ? `${n}.0` : String(n));
const list = (xs) => xs.map(num).join(', ');
const pairs = (name, rows) =>
  `constexpr IndexedValue ${name}[] = {${rows.map(([i, x]) => `{${i}, ${num(x)}}`).join(', ')}};\n` +
  `constexpr int ${name}Count = ${rows.length};\n`;

function resolveMatrix(ref) {
  if (ref === 'perspective') return v.mat4.perspective.expected;
  const m = ref.match(/^lookAt\[(\d+)\]$/);
  if (!m) throw new Error(`unknown matrix ref ${ref}`);
  return v.mat4.lookAt[Number(m[1])].expected;
}

const lookAtCases = v.mat4.lookAt
  .map((c) => `    {{${list(c.eye)}}, {${list(c.target)}}, {${list(c.up)}}, {${list(c.expected)}}}`)
  .join(',\n');
const mipCases = v.sampler.colorByMipLevels
  .map((c) => `    {${c.levels}, ${c.lodMaxClamp}, ${c.maxAnisotropy}, ${c.viewMipLevels}}`)
  .join(',\n');

const header = `// GENERATED by scripts/generate-cpp-test-vectors.mjs from shared/cppParityVectors.json.
// Do not edit; this file is gitignored and rebuilt on every native-test build.
#pragma once

#include <cstdint>

namespace parity {

struct IndexedValue {
  int index;
  double value;
};

struct LookAtCase {
  double eye[3];
  double target[3];
  double up[3];
  double expected[16];
};

struct MipCase {
  uint32_t levels;
  uint32_t lod_max_clamp;
  uint16_t max_anisotropy;
  uint32_t view_mip_levels;
};

constexpr double kTolerance = ${num(v.tolerance)};

constexpr int kCols = ${v.board.cols};
constexpr int kRows = ${v.board.rows};
constexpr int kPlayfieldBytes = ${v.board.playfieldBytes};
constexpr double kBlockWorldSize = ${num(v.board.blockWorldSize)};
constexpr double kCenterX = ${num(v.board.centerX)};
constexpr double kCenterY = ${num(v.board.centerY)};

${pairs('kWorldX', v.board.worldX)}${pairs('kWorldY', v.board.worldY)}${pairs('kBlockCenterX', v.board.blockCenterX)}${pairs('kBlockCenterY', v.board.blockCenterY)}
constexpr double kCameraZ = ${num(v.camera.z)};
constexpr double kCameraFovDeg = ${num(v.camera.fovDeg)};
constexpr double kCameraNear = ${num(v.camera.near)};
constexpr double kCameraFar = ${num(v.camera.far)};

constexpr int kPieceStateSize = ${v.pieceState.sizeBytes};
constexpr int kOffsetPieceType = ${v.pieceState.offsets.pieceType};
constexpr int kOffsetRotation = ${v.pieceState.offsets.rotation};
constexpr int kOffsetX = ${v.pieceState.offsets.x};
constexpr int kOffsetY = ${v.pieceState.offsets.y};
constexpr int kOffsetGhostY = ${v.pieceState.offsets.ghostY};
constexpr int kOffsetLockFlash = ${v.pieceState.offsets.lockFlash};

constexpr uint32_t kSamplerMaxLod = ${v.sampler.maxLod};
constexpr uint16_t kSamplerMaxAnisotropy = ${v.sampler.maxAnisotropy};
constexpr double kColorLodMinClamp = ${num(v.sampler.color.lodMinClamp)};
constexpr double kMaskLodMinClamp = ${num(v.sampler.mask.lodMinClamp)};
constexpr double kMaskLodMaxClamp = ${num(v.sampler.mask.lodMaxClamp)};
constexpr MipCase kColorByMipLevels[] = {
${mipCases}};
constexpr int kColorByMipLevelsCount = ${v.sampler.colorByMipLevels.length};

constexpr double kPerspectiveFovYDeg = ${num(v.mat4.perspective.fovYDeg)};
constexpr double kPerspectiveAspect = ${num(v.mat4.perspective.aspect)};
constexpr double kPerspectiveNear = ${num(v.mat4.perspective.near)};
constexpr double kPerspectiveFar = ${num(v.mat4.perspective.far)};
constexpr double kPerspectiveExpected[16] = {${list(v.mat4.perspective.expected)}};
constexpr LookAtCase kLookAtCases[] = {
${lookAtCases}};
constexpr int kLookAtCaseCount = ${v.mat4.lookAt.length};
constexpr double kMultiplyA[16] = {${list(resolveMatrix(v.mat4.multiply.a))}};
constexpr double kMultiplyB[16] = {${list(resolveMatrix(v.mat4.multiply.b))}};
constexpr double kMultiplyExpected[16] = {${list(v.mat4.multiply.expected)}};

} // namespace parity
`;

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT_HEADER, header);
console.log(`[generate-cpp-test-vectors] Wrote ${OUT_HEADER}`);
