/**
 * Node-side reader/validator for the CPU opponent's shared data files, plus the AssemblyScript
 * code generator. Mirror of src/bot/botData.ts: both read shared/botDataSchema.json, so the build
 * gate and the runtime agree on what a valid file is.
 */

import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');

export const SCHEMA_PATH = join(ROOT, 'shared', 'botDataSchema.json');
export const ATTACK_PATH = join(ROOT, 'shared', 'versusAttack.json');
export const WEIGHTS_PATH = join(ROOT, 'shared', 'botWeights.json');
export const GENERATED_PATH = join(ROOT, 'assembly', 'bot', 'generated.ts');

const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'));

export function loadBotData() {
  return {
    schema: readJson(SCHEMA_PATH),
    attack: readJson(ATTACK_PATH),
    weights: readJson(WEIGHTS_PATH),
  };
}

function isObject(v) {
  return v != null && typeof v === 'object' && !Array.isArray(v);
}

/** @returns {string[]} human-readable problems; empty when valid. */
export function validateBotData({ schema, attack, weights }) {
  const errors = [];

  if (!isObject(attack)) {
    errors.push('versusAttack.json must be a JSON object');
  } else {
    for (const name of schema.attack.tables) {
      const table = attack[name];
      if (!Array.isArray(table) || table.length !== schema.attack.length) {
        errors.push(`versusAttack.${name}: expected an array of ${schema.attack.length} entries`);
        continue;
      }
      table.forEach((v, i) => {
        if (!Number.isInteger(v) || v < schema.attack.min || v > schema.attack.max) {
          errors.push(`versusAttack.${name}[${i}]: ${JSON.stringify(v)} is not an integer in ${schema.attack.min}..${schema.attack.max}`);
        }
      });
      if (table[0] !== 0) errors.push(`versusAttack.${name}[0]: zero lines must send 0`);
    }
    for (const key of Object.keys(attack)) {
      if (key !== '$comment' && key !== 'version' && !schema.attack.tables.includes(key)) {
        errors.push(`versusAttack.${key}: unknown table (not in botDataSchema.json)`);
      }
    }
  }

  if (!isObject(weights) || !isObject(weights.weights)) {
    errors.push('botWeights.json must be an object with a "weights" object');
  } else {
    const { features, min, max, capacity } = schema.weights;
    if (features.length > capacity) errors.push(`schema declares ${features.length} features > capacity ${capacity}`);
    for (const name of features) {
      const v = weights.weights[name];
      if (typeof v !== 'number' || !Number.isFinite(v)) {
        errors.push(`botWeights.weights.${name}: required finite number, got ${JSON.stringify(v)}`);
      } else if (v < min || v > max) {
        errors.push(`botWeights.weights.${name}: ${v} outside ${min}..${max}`);
      }
    }
    for (const key of Object.keys(weights.weights)) {
      if (!features.includes(key)) errors.push(`botWeights.weights.${key}: unknown feature (not in botDataSchema.json)`);
    }
  }
  return errors;
}

const SNAKE = (s) => s.replace(/([A-Z])/g, '_$1').toUpperCase();

/** Fixed-width float literal that AssemblyScript parses as f32 exactly like Math.fround would. */
function f32Literal(v) {
  const s = String(v);
  return /[.eE]/.test(s) ? s : `${s}.0`;
}

/** The text of assembly/bot/generated.ts. Deterministic: the committed file is diffed against it. */
export function renderGenerated({ schema, attack, weights }) {
  const { features, capacity } = schema.weights;
  const lines = [
    '// GENERATED by scripts/generate-bot-constants.mjs from shared/versusAttack.json,',
    '// shared/botWeights.json and shared/botDataSchema.json. Do not edit by hand:',
    '// `npm run bot:generate` rewrites it, `npm run bot:generate -- --check` (and the test suite) fails if stale.',
    '',
    `export const WEIGHT_CAPACITY: i32 = ${capacity};`,
    `export const WEIGHT_COUNT: i32 = ${features.length};`,
    '',
  ];
  features.forEach((name, i) => lines.push(`export const W_${SNAKE(name)}: i32 = ${i};`));
  lines.push('', '// NO STATIC DATA (see assembly/bot/layout.ts): the tables are code, executed by botInit().');
  lines.push('// Default weights, schema order; slots past WEIGHT_COUNT are zeroed by the caller.');
  lines.push('export function loadDefaultWeights(dst: i32): void {');
  features.forEach((name, i) => {
    lines.push(`  store<f32>(dst + ${i * 4}, ${f32Literal(weights.weights[name])}); // ${name}`);
  });
  lines.push('}', '');
  lines.push('// Garbage rows by lines cleared (index 0..4): plain, T-spin mini, full T-spin.');
  for (const name of schema.attack.tables) {
    const arr = attack[name];
    lines.push(`export function attack${name[0].toUpperCase()}${name.slice(1)}(lines: i32): i32 {`);
    arr.forEach((v, i) => lines.push(`  if (lines == ${i}) return ${v};`));
    lines.push(`  return ${arr[arr.length - 1]};`, '}', '');
  }
  return lines.join('\n');
}
